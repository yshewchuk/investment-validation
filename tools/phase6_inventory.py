#!/usr/bin/env python3
"""P6-1: generate the Phase 6 capability matrix and adapter/read-set inventory.

Two halves, kept apart on purpose:

* **Discovery** reads the actual source with :mod:`ast` and regular
  expressions — never an import of ``engine.*``, so nothing loads a panel.
  It finds every consumer entrypoint: the legacy FastAPI routes, the v2
  API and operations-server routes, the legacy SPA views and controls, the
  React routes, every ``__main__`` CLI and argparse subcommand, the legacy
  nightly steps, the v2 nightly DAG stages, the supervised legacy actions,
  the coordinator effects, and the legacy ledger/report/export/backup
  writers. It also finds every v2 -> legacy adapter edge: the exact-symbol
  ledger ``checks/legacy_adapters.json`` plus the file-format adapter
  modules.
* **Declarations** (``tools/phase6_capabilities.toml``) carry the judgement
  a parser cannot make: which capability an entrypoint belongs to, its
  disposition and owning phase. The generated matrix joins the two and
  records, per row, whether each claimed new entrypoint and test resolves.

``checks/phase6_inventory.py`` turns the joined document into findings.
This tool only reports; it always exits 0 unless its inputs cannot be read.

Usage::

    python3 tools/phase6_inventory.py                       # summary only
    python3 tools/phase6_inventory.py --out /tmp/p6.json    # full document
    python3 tools/phase6_inventory.py --write-guide         # refresh the guide section

No data value is read: only source files, file names and the declarations.
"""

def _is_main_guard(node: ast.AST) -> bool:
    return (isinstance(node, ast.If) and isinstance(node.test, ast.Compare)
            and isinstance(node.test.left, ast.Name) and node.test.left.id == "__name__")


def _main_modules(root: Path) -> list[str]:
    result = []
    for top in CLI_ROOTS:
        for path in sorted((root / top).rglob("*.py")):
            rel = path.relative_to(root).as_posix()
            if "__pycache__" in rel:
                continue
            tree = ast.parse(path.read_text(), filename=rel)
            if path.name == "__main__.py" or any(_is_main_guard(n) for n in tree.body):
                result.append(rel)
    return result


def _clis(root: Path, found: dict) -> None:
    for rel in _main_modules(root):
        _add(found, f"cli:{rel}", "cli", rel)
    runners = sorted(root.glob(EXPERIMENT_GLOB))
    if runners:
        _add(found, f"cli-family:{EXPERIMENT_GLOB}", "cli", f"{len(runners)} runners")


def _loop_values(tree: ast.AST) -> dict[int, list[str]]:
    """``for name in ("a", "b"): x.add_parser(name)`` -> {call id: [a, b]}."""
    result = {}
    for loop in (n for n in ast.walk(tree) if isinstance(n, ast.For)):
        values = _const_strings(loop.iter)
        if not (values and isinstance(loop.target, ast.Name)):
            continue
        for call in ast.walk(loop):
            if (isinstance(call, ast.Call) and isinstance(call.func, ast.Attribute)
                    and call.func.attr == "add_parser" and call.args
                    and isinstance(call.args[0], ast.Name) and call.args[0].id == loop.target.id):
                result[id(call)] = values
    return result


def _subcommands(root: Path, rel: str, prefix: str, found: dict) -> None:
    """argparse ``add_subparsers``/``add_parser`` chains, nested by variable."""
    tree = _tree(root, rel)
    looped = _loop_values(tree)
    paths: dict[str, tuple[str, ...]] = {}
    assigns = sorted((n for n in ast.walk(tree) if isinstance(n, (ast.Assign, ast.Expr))),
                     key=lambda n: (n.lineno, n.col_offset))
    for node in assigns:
        call = node.value
        if not (isinstance(call, ast.Call) and isinstance(call.func, ast.Attribute)
                and isinstance(call.func.value, ast.Name)):
            continue
        parent = paths.get(call.func.value.id, ())
        target = node.targets[0].id if isinstance(node, ast.Assign) and isinstance(
            node.targets[0], ast.Name) else None
        if call.func.attr == "add_subparsers" and target:
            paths[target] = parent
        elif call.func.attr == "add_parser":
            names = looped.get(id(call)) or _const_strings(ast.Tuple(elts=call.args[:1]))
            for name in names:
                _add(found, f"cli:{prefix} " + " ".join(parent + (name,)), "subcommand", rel)
            if target and len(names) == 1:
                paths[target] = parent + (names[0],)



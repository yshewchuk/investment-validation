def _legacy_imports(tree: ast.Module) -> bool:
    for node in ast.walk(tree):
        names = [node.module or ""] if isinstance(node, ast.ImportFrom) and node.level == 0 else (
            [a.name for a in node.names] if isinstance(node, ast.Import) else [])
        if any((n == "engine" or n.startswith("engine.")) and not n.startswith("engine.v2") for n in names):
            return True
    return False


def adapter_modules(root: Path = ROOT) -> list[str]:
    """v2-side modules that touch the legacy runtime or a legacy file format:
    named ``*legacy*``/``*compat*``/``*bridge*``/``*adapter*``, or importing
    a non-v2 ``engine.*`` module, under ``engine/v2`` and ``tools/v2_*``."""
    candidates = sorted((root / "engine/v2").rglob("*.py")) + sorted((root / "tools").glob("v2_*.py"))
    result = []
    for path in candidates:
        rel = path.relative_to(root).as_posix()
        if "__pycache__" in rel:
            continue
        if _ADAPTER_NAME.search(path.name) or _legacy_imports(ast.parse(path.read_text(), filename=rel)):
            result.append(rel)
    return result


def ledger_edges(root: Path = ROOT) -> list[dict]:
    """One edge per exact-symbol entry of ``checks/legacy_adapters.json``."""
    ledger = json.loads((root / ADAPTER_LEDGER).read_text())
    return [{"id": f"edge:{a['module']}::{a['legacy_symbol']}", "module": a["module"],
             "legacy_symbol": a["legacy_symbol"], "reads": a.get("read_set", ""),
             "ledger_removal_phase": a.get("removal_phase", "")}
            for a in ledger["adapters"]]



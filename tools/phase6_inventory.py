def _legacy_nightly_steps(root: Path, found: dict) -> None:
    text = _text(root, LEGACY_NIGHTLY)
    steps = set(re.findall(r'report\.mark\("(\w+)"', text)) | set(re.findall(r'report\.steps\["(\w+)"\]', text))
    for step in sorted(steps):
        _add(found, f"nightly:legacy {step}", "nightly-step", LEGACY_NIGHTLY)


def _v2_nightly_stages(root: Path, found: dict) -> None:
    tree = _tree(root, V2_NIGHTLY)
    stages = set(_const_strings(_module_assign(tree, "_DAG_STAGES")))
    graph = _module_assign(tree, "GRAPH")
    if isinstance(graph, ast.Dict):
        stages |= {k.value for k in graph.keys if isinstance(k, ast.Constant)}
    for node in ast.walk(tree):  # ("materialize",) + stages
        if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add) and isinstance(node.left, ast.Tuple):
            if isinstance(node.right, ast.Name) and node.right.id == "stages":
                stages |= set(_const_strings(node.left))
    for stage in sorted(stages):
        _add(found, f"nightly:v2 {stage}", "dag-stage", V2_NIGHTLY)


def _functions(tree: ast.Module):
    for node in tree.body:
        if isinstance(node, ast.FunctionDef):
            yield node.name, node
        elif isinstance(node, ast.ClassDef):
            for member in node.body:
                if isinstance(member, ast.FunctionDef):
                    yield f"{node.name}.{member.name}", member


def _v2_actions_and_effects(root: Path, found: dict) -> None:
    for name, _ in _functions(_tree(root, V2_ACTIONS)):
        if name.startswith("_action_"):
            _add(found, "action:legacy_" + name.removeprefix("_action_"), "action", V2_ACTIONS)
    for name, _ in _functions(_tree(root, V2_EFFECTS)):
        if name.endswith("_effect") and not name.startswith("_"):
            _add(found, f"effect:{name}", "effect", V2_EFFECTS)


def _called_names(fn: ast.AST) -> set[str]:
    return {c.func.attr if isinstance(c.func, ast.Attribute) else getattr(c.func, "id", "")
            for c in ast.walk(fn) if isinstance(c, ast.Call)}


def writer_functions(tree: ast.Module) -> list[str]:
    """Public functions that write a file, directly or through a same-module
    helper (transitive closure), excluding ``main`` (covered as a CLI)."""
    calls = {name: _called_names(fn) for name, fn in _functions(tree)}
    short = {name.rsplit(".", 1)[-1] for name in calls}
    writers = {name for name, called in calls.items() if called & _WRITE_CALLS}
    changed = True
    while changed:
        names = {w.rsplit(".", 1)[-1] for w in writers}
        grown = {n for n, called in calls.items() if called & names & short} - writers
        writers |= grown
        changed = bool(grown)
    return sorted(w for w in writers if not any(p.startswith("_") for p in w.split("."))
                  and w != "main")


def _writers(root: Path, found: dict) -> None:
    for rel in WRITER_MODULES:
        for name in writer_functions(_tree(root, rel)):
            _add(found, f"writer:{rel}::{name}", "writer", rel)


def discover_entrypoints(root: Path = ROOT) -> dict[str, dict]:
    """Every consumer entrypoint id -> {kind, source}. Deterministic order."""
    found: dict[str, dict] = {}
    _fastapi_routes(root, LEGACY_APP, "legacy-app", found)
    _fastapi_routes(root, V2_API, "v2-api", found)
    _handler_routes(root, V2_OPS_SERVER, "v2-ops", found)
    _declared_routes(root, V2_OPS_SERVER, "v2-ops", found)
    _spa_views(root, found)
    _spa_controls(root, found)
    _react_routes(root, found)
    _clis(root, found)
    for rel, prefix in SUBCOMMAND_CLIS.items():
        _subcommands(root, rel, prefix, found)
    _legacy_nightly_steps(root, found)
    _v2_nightly_stages(root, found)
    _v2_actions_and_effects(root, found)
    _writers(root, found)
    return dict(sorted(found.items()))



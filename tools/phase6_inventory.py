def _cell(values) -> str:
    text = "<br>".join(f"`{v}`" for v in values) if isinstance(values, list) else str(values)
    return (text or "-").replace("|", "\\|").replace("\n", " ")


def counts(document: dict) -> dict[str, int]:
    result = {d: 0 for d in DISPOSITIONS}
    for row in document["rows"]:
        result[row["disposition"]] = result.get(row["disposition"], 0) + 1
    return result


def _tally(items, key) -> str:
    result: dict[str, int] = {}
    for item in items:
        result[item[key] or "UNOWNED"] = result.get(item[key] or "UNOWNED", 0) + 1
    return ", ".join(f"{k} {v}" for k, v in sorted(result.items()))


def _matrix_lines(document: dict) -> list[str]:
    lines = ["| Row | Capability | Old entrypoint | New v2 entrypoint | Producer | Snapshot/release identity "
             "| Tests | Disposition | Owner |", "|---|---|---|---|---|---|---|---|---|"]
    for area in REQUIRED_AREAS:
        for row in (r for r in document["rows"] if r["area"] == area):
            status = row["disposition"] + ("" if row["active"] else " (dormant reader)")
            lines.append("| " + " | ".join([
                f"`{row['id']}`", _cell(row["capability"]), _cell(row["old"]), _cell(row["new"]),
                _cell(row["producer"]), _cell(row["identity"]), _cell(row["tests"]), status,
                row["owner"]]) + " |")
    return lines


def _missing_lines(document: dict) -> list[str]:
    lines = ["| Row | Missing capability | Owner | What is missing |", "|---|---|---|---|"]
    for row in document["rows"]:
        if row["disposition"] == "missing" or "MISSING" in row["new"]:
            lines.append(f"| `{row['id']}` | {_cell(row['capability'])} | {row['owner']} | {_cell(row['notes'])} |")
    return lines


def _edge_lines(document: dict) -> list[str]:
    lines = ["| Edge | Kind | Reads | Consumer | Owner (removal) | Ledger label |", "|---|---|---|---|---|---|"]
    for edge in document["adapter_edges"]:
        lines.append(f"| `{edge['id'].removeprefix('edge:')}` | {edge['kind']} | {_cell(edge['reads'])} | "
                     f"{_cell(edge['consumer'])} | {edge['owner'] or 'UNOWNED'} | "
                     f"{_cell(edge['ledger_removal_phase'])} |")
    return lines


def render_markdown(document: dict) -> str:
    tally = counts(document)
    lines = [GUIDE_BEGIN, "", f"Schema `{SCHEMA_VERSION}`: {len(document['discovered'])} discovered "
             f"entrypoints, {len(document['rows'])} capability rows, "
             f"{sum(len(e['ids']) for e in document['excluded'])} excluded tooling entrypoints, "
             f"{len(document['adapter_edges'])} adapter edges.", "",
             "Rows per disposition: " + ", ".join(f"{k} {v}" for k, v in tally.items()) + ".", "",
             "Rows per owner: " + _tally(document["rows"], "owner") + ".", "",
             "Adapter edges per owner: " + _tally(document["adapter_edges"], "owner") + ".",
             "", "#### Capability matrix", ""]
    lines += _matrix_lines(document)
    lines += ["", "#### MISSING capabilities (the P6-2..P6-5 work)", ""] + _missing_lines(document)
    lines += ["", "#### Needs a user decision", ""]
    lines += [f"- **{d['id']}** ({_cell(d['rows'])}): {d['question']}"
              for d in document["user_decisions"]] or ["- none"]
    lines += ["", "#### Excluded entrypoints (migration and verification tooling, not consumers)", ""]
    lines += [f"- {_cell(e['ids'])}: {e['reason']}" for e in document["excluded"]]
    lines += ["", "#### Active adapter and read-set inventory", ""] + _edge_lines(document)
    lines += ["", GUIDE_END]
    return "\n".join(lines) + "\n"


def guide_block(text: str) -> str | None:
    start, end = text.find(GUIDE_BEGIN), text.find(GUIDE_END)
    if start < 0 or end < start:
        return None
    return text[start:end + len(GUIDE_END)] + "\n"


def write_guide(root: Path, markdown: str) -> None:
    path = root / GUIDE
    text = path.read_text()
    current = guide_block(text)
    if current is None:
        raise SystemExit(f"{GUIDE}: no generated-section marker; add the section first")
    path.write_text(text.replace(current, markdown))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--declarations", type=Path, default=None)
    parser.add_argument("--out", type=Path, default=None, help="write the full JSON document here")
    parser.add_argument("--write-guide", action="store_true", help="refresh the generated guide section")
    args = parser.parse_args(argv)
    document = build_document(args.root, args.declarations)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(json.dumps(document, indent=2) + "\n")
    if args.write_guide:
        write_guide(args.root, render_markdown(document))
    print(f"discovered {len(document['discovered'])} entrypoints; {len(document['rows'])} rows; "
          f"{len(document['adapter_edges'])} adapter edges")
    print("dispositions: " + ", ".join(f"{k}={v}" for k, v in counts(document).items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())

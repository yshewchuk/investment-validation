def load_declarations(path: Path) -> dict:
    with path.open("rb") as handle:
        return tomllib.load(handle)


def _symbols(tree: ast.Module) -> set[str]:
    names = {name for name, _ in _functions(tree)}
    names |= {n.name for n in tree.body if isinstance(n, ast.ClassDef)}
    for node in tree.body:
        if isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            names |= {t.id for t in targets if isinstance(t, ast.Name)}
    return names


def resolve_symbol(root: Path, ref: str) -> bool:
    """``path`` or ``path::Symbol`` / ``path::Class::method`` exists in source.
    ``.py`` files are parsed; any other file is searched for the symbol text."""
    rel, _, symbol = ref.partition("::")
    path = root / rel
    if not path.is_file():
        return False
    if not symbol:
        return True
    if path.suffix == ".py":
        return symbol.replace("::", ".") in _symbols(ast.parse(path.read_text(), filename=rel))
    return re.search(rf"\b{re.escape(symbol)}\b", path.read_text()) is not None


def _job_kind_names(root: Path) -> set[str]:
    """The supervised job kinds the runtime registry actually allows.

    A ``job:<kind>`` declaration names the allowlist entry itself rather than
    a path into the tools, so it resolves against the source that owns the
    registry. For the real repository root the runtime registry is the one
    authority -- it also knows every kind built in a loop rather than a
    literal ``JobKind(...)`` call (the outbox effects, the legacy action
    family, ``incremental_refresh``). A synthetic test tree gets the AST scan
    fallback, because importing this checkout's registry would answer for the
    wrong tree; the file is absent only in synthetic trees that claim no job
    kind, which resolve to the empty set.
    """
    if root.resolve() == ROOT.resolve():
        from engine.v2.ops.stages import registry

        return set(registry().names())
    path = root / V2_STAGES
    if not path.is_file():
        return set()
    names = set()
    for node in ast.walk(ast.parse(path.read_text(), filename=V2_STAGES)):
        if (isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
                and node.func.id == "JobKind"):
            for keyword in node.keywords:
                if (keyword.arg == "name" and isinstance(keyword.value, ast.Constant)
                        and isinstance(keyword.value.value, str)):
                    names.add(keyword.value.value)
    return names


def resolve_entrypoint(root: Path, ref: str, discovered: dict) -> bool:
    if ref.startswith("py:"):
        return resolve_symbol(root, ref.removeprefix("py:"))
    if ref.startswith("job:"):
        return ref.removeprefix("job:") in _job_kind_names(root)
    return ref in discovered


def _row(root: Path, row: dict, discovered: dict) -> dict:
    new = list(row.get("new", []))
    tests = list(row.get("tests", []))
    return {
        "id": row.get("id", ""), "area": row.get("area", ""), "capability": row.get("capability", ""),
        "old": list(row.get("old", [])), "new": new,
        "new_resolved": {ref: resolve_entrypoint(root, ref, discovered) for ref in new if ref != "MISSING"},
        "producer": row.get("producer", ""), "identity": row.get("identity", ""),
        "tests": tests, "tests_resolved": {t: resolve_symbol(root, t) for t in tests},
        "disposition": row.get("disposition", ""), "owner": row.get("owner", ""),
        "active": bool(row.get("active", True)), "interactive": bool(row.get("interactive", False)),
        "decision": row.get("decision", ""), "notes": row.get("notes", ""),
    }


def _edges(root: Path, decl: dict) -> list[dict]:
    owner_map = decl.get("edge_owner_map", {})
    consumers = decl.get("edge_consumer_map", {})
    overrides = {o["id"]: o for o in decl.get("edge_override", [])}
    edges = []
    for edge in ledger_edges(root):
        override = overrides.get(edge["id"], {})
        edge.update(kind="exact-symbol",
                    owner=override.get("owner", owner_map.get(edge["ledger_removal_phase"], "")),
                    consumer=override.get("consumer", consumers.get(edge["module"], "")),
                    active=override.get("active", True), notes=override.get("notes", ""),
                    module_exists=True)
        edges.append(edge)
    for edge in decl.get("edge", []):
        edges.append({"id": edge.get("id", ""), "kind": edge.get("kind", "file-format"),
                      "module": edge.get("module", ""), "legacy_symbol": "",
                      "reads": edge.get("reads", ""), "ledger_removal_phase": "",
                      "owner": edge.get("owner", ""), "consumer": edge.get("consumer", ""),
                      "active": edge.get("active", True), "notes": edge.get("notes", ""),
                      "module_exists": resolve_symbol(root, edge.get("module", ""))})
    return edges


def build_document(root: Path = ROOT, declarations: Path | None = None,
                   discovered: dict | None = None) -> dict:
    decl = load_declarations(root / (declarations or DECLARATIONS))
    discovered = discover_entrypoints(root) if discovered is None else discovered
    rows = [_row(root, row, discovered) for row in decl.get("row", [])]
    excluded = [{"ids": list(e.get("ids", [])), "reason": e.get("reason", "")}
                for e in decl.get("excluded", [])]
    return {"schema_version": SCHEMA_VERSION, "discovered": discovered, "rows": rows,
            "excluded": excluded, "adapter_modules": adapter_modules(root),
            "adapter_edges": _edges(root, decl), "user_decisions": list(decl.get("user_decision", []))}



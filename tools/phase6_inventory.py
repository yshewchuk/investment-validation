def _text(root: Path, rel: str) -> str:
    return (root / rel).read_text()


def _tree(root: Path, rel: str) -> ast.Module:
    return ast.parse(_text(root, rel), filename=rel)


def _const_strings(node: ast.AST) -> list[str]:
    if isinstance(node, (ast.Tuple, ast.List, ast.Set)):
        return [e.value for e in node.elts if isinstance(e, ast.Constant) and isinstance(e.value, str)]
    return []


def _module_assign(tree: ast.Module, name: str) -> ast.AST | None:
    for node in tree.body:
        targets = node.targets if isinstance(node, ast.Assign) else (
            [node.target] if isinstance(node, ast.AnnAssign) else [])
        if any(isinstance(t, ast.Name) and t.id == name for t in targets):
            return node.value
    return None


def _add(found: dict, ident: str, kind: str, source: str) -> None:
    found.setdefault(ident, {"kind": kind, "source": source})



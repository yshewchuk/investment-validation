REGISTERED_RUNNER = "experiments/EXP-182_d_1_gated_execution_parity_registered/run.py"

TINY_RUNNER = '''\
import json
from pathlib import Path

root = Path.cwd()
(root / "REPORT.md").write_text(
    "# Tiny synthetic experiment\\n\\n*Generated by engine.report v1.0.*\\n")
results = root / "results"
results.mkdir(exist_ok=True)
(results / "metrics_test.json").write_text(
    json.dumps({"headline": {"mean": 0.02, "sharpe_trade": 1.5}}))
'''

TINY_RUNNER_NO_METRICS = TINY_RUNNER.split("results = root")[0]


def _tiny_checkout(tmp_path, *, with_metrics=True):
    """A tmp checkout with the registered runner, its legacy spec.yaml and a
    PLANNED ledger row; returns ``(checkout, spec_path, ledger, planned_hash)``."""
    from experiments import lib

    checkout = tmp_path / "checkout"
    runner = checkout / REGISTERED_RUNNER
    runner.parent.mkdir(parents=True)
    runner.write_text(TINY_RUNNER if with_metrics else TINY_RUNNER_NO_METRICS)
    legacy_spec = runner.parent / "spec.yaml"
    legacy_spec.write_text("id: EXP-182\nprimary_spec:\n  x: 1\n")
    planned_hash = lib.spec_hash(lib.load_spec(legacy_spec))
    ledger = checkout / "experiments" / "LEDGER.csv"
    lib.ledger_append([{"id": "EXP-182", "spec_hash": planned_hash,
                        "date": "2026-01-01", "stage": "planned",
                        "oos_mean_mid": "", "sharpe_trade": "", "promoted": "False"}],
                      path=ledger)
    spec_path = checkout / "spec.json"
    spec_path.write_text(json.dumps(_experiment_document(
        experiment_id="EXP-182", runner=REGISTERED_RUNNER, economic_params={})))
    return checkout, spec_path, ledger, planned_hash


def _planned_parameters(tmp_path, checkout, spec_path, capsys, monkeypatch):
    monkeypatch.setattr(experiments, "default_checkout_root", lambda: checkout)
    ops = tmp_path / "ops"
    assert cli.main(["--root", str(ops), "init"]) == 0
    capsys.readouterr()
    assert cli.main(["--root", str(ops), "plan", "experiment", "--spec", str(spec_path),
                     "--activate-ledger"]) == 0
    return ops, json.loads(capsys.readouterr().out)["plan"]


def test_ops_plan_worker_and_legacy_runner_report_reaches_the_checkout_ledger(
        tmp_path, monkeypatch, capsys):
    """The production wiring end to end without market data: a primary plan
    from the real CLI, the worker dispatch that calls ``run_legacy_script``,
    the registered runner's own REPORT.md/results, and the coordinator's ran
    row in the CHECKOUT ledger with the planned row's spec_hash."""
    checkout, spec_path, ledger, planned_hash = _tiny_checkout(tmp_path)
    ops, plan = _planned_parameters(tmp_path, checkout, spec_path, capsys, monkeypatch)

    result = worker.dispatch("experiment", plan["parameters"], checkout)
    assert result["completed_ids"] == ["experiment:EXP-182"]
    assert [output["name"] for output in result["outputs"]] == [
        "experiment_receipt", "resolved_experiment_plan", "experiment_variant_report"]
    plan_artifact = checkout / "resolved_experiment_plan.json"
    assert plan_artifact.is_file()
    persisted = plan_artifact.read_bytes()
    assert persisted == experiments.resolve_experiment_plan(
        experiment_spec_from_document(json.loads(spec_path.read_text()))).json_bytes()
    assert persisted == json.dumps(json.loads(persisted), sort_keys=True,
                                   separators=(",", ":"), ensure_ascii=False).encode("utf-8")
    assert json.loads(persisted)["schema_version"] == "experiment_execution_plan.v1.0"
    receipt = json.loads((checkout / "experiment_receipt.json").read_text())
    assert receipt["status"] == "succeeded"
    assert receipt["evidence"]["report_bytes"] > 0
    report_text = (checkout / "REPORT.md").read_text()
    assert "by engine.report v" in report_text
    assert "Tiny synthetic experiment" in report_text

    document = json.loads(spec_path.read_text())
    spec = experiments.experiment_spec_from_document(document)
    conn, _clock, _ = catalog(ops)
    try:
        effects_graph._append_ledger_row(conn, checkout, spec, receipt, run_id="exp-run")
    finally:
        conn.close()

    from experiments import lib

    frame = lib.ledger_read(ledger).fillna("")
    ran = frame[frame["stage"] == "ran"].iloc[-1]
    assert ran["spec_hash"] == planned_hash, "planned and ran rows must join"
    assert float(ran["oos_mean_mid"]) == pytest.approx(0.02)
    assert float(ran["sharpe_trade"]) == pytest.approx(1.5)
    assert "notes" not in frame.columns, "the legacy ledger format stays at 7 columns"
    assert not (ops / "experiments").exists()

    refused = tmp_path / "refused"
    refused.mkdir()
    (refused / "spec.json").write_text(json.dumps(_experiment_document(
        experiment_id="EXP-182", runner=REGISTERED_RUNNER)))
    with pytest.raises(OpsError) as excinfo:
        worker.dispatch("experiment", {"expected_ids": ["experiment:EXP-182"],
                                       "runner": REGISTERED_RUNNER, "no_ledger": True}, refused)
    assert excinfo.value.code == "INVALID_EXPERIMENT_SPEC"
    assert not (refused / "resolved_experiment_plan.json").exists()
    assert not (refused / "experiment_receipt.json").exists()


def test_ran_row_records_metrics_source_unavailable_when_the_runner_wrote_none(tmp_path):
    """Review fix item 5: no results JSON -> empty headline columns, the
    legacy ledger keeps its fixed 7 columns, and the durable run's evidence
    records ``metrics_source: unavailable``."""
    checkout, spec_path, ledger, _planned_hash = _tiny_checkout(tmp_path, with_metrics=False)
    document = json.loads(spec_path.read_text())
    spec = experiments.experiment_spec_from_document(document)
    ops = tmp_path / "ops"
    ops.mkdir()
    conn, _clock, _ = catalog(ops)
    try:
        with transaction(conn):
            run_id, _created = experiments.register_hypothesis_in_transaction(
                conn, spec, "input-unavailable", mode="primary")
        effects_graph._append_ledger_row(
            conn, checkout, spec,
            {"status": "succeeded", "evidence": {"runner_result": {"returncode": 0}}},
            run_id=run_id)

        from experiments import lib

        ran = lib.ledger_read(ledger).fillna("").iloc[-1]
        assert ran["stage"] == "ran"
        assert ran["oos_mean_mid"] == "" and ran["sharpe_trade"] == ""
        assert "notes" not in lib.ledger_read(ledger).columns
        evidence = json.loads(conn.execute(
            "SELECT evidence_json FROM experiment_runs WHERE run_id=?",
            (run_id,)).fetchone()[0])
        assert evidence["metrics_source"] == "unavailable"
    finally:
        conn.close()


def test_no_ledger_smoke_binds_report_identity_to_consumed_economics(tmp_path):
    """Review-fix regression for #166 and #295 through the variant-report path.

    Two smoke runs share one plan-aware runner and differ only in the declared
    economics (``fill=mid`` then ``fill=ask``). The variant ID is derived by
    omitting the optional ``variant_id``, so each receipt and report identity
    must be exactly its own spec's ``spec_hash``, and the two spec hashes are
    distinct. Every call carries ``no_ledger=True``, the consumer sees each
    distinct fill, and no ``experiments`` ``LEDGER.csv`` exists anywhere under
    the test root. An economically invalid plan is refused typed -- also with
    no manual variant ID -- before the runner runs and before any directory,
    report, receipt, or ledger effect exists.
    """
    calls: list[tuple[bool, str]] = []

    def plan_aware_runner(*, run_dir, no_ledger, execution_plan):
        if no_ledger is not True:
            raise AssertionError("a test runner must require no_ledger=True")
        calls.append((no_ledger, execution_plan.economic_params["fill"]))
        (run_dir / "REPORT.md").write_text("# No-ledger smoke probe\n\n"
                                           "*Generated by engine.report v1.0.*\n")
        return {"fixture": True, "no_ledger": no_ledger}

    variants = {}
    for fill in ("mid", "ask"):
        spec = experiment_spec_from_document(
            _experiment_document(economic_params={"fill": fill}))
        variant_id = spec.spec_hash
        run_dir = tmp_path / f"run-{fill}"
        receipt = experiments.run_experiment(spec, tmp_path, run_dir,
                                              runner=plan_aware_runner, mode="smoke")
        variants[fill] = (receipt, run_dir, variant_id)

    assert [no_ledger for no_ledger, _fill in calls] == [True, True]
    assert [fill for _no_ledger, fill in calls] == ["mid", "ask"]

    mid_receipt = variants["mid"][0]
    ask_receipt = variants["ask"][0]
    assert mid_receipt["status"] == "succeeded" and ask_receipt["status"] == "succeeded"
    assert variants["mid"][2] != variants["ask"][2], "distinct economics, distinct spec hashes"
    assert mid_receipt["evidence"]["variant_id"] != ask_receipt["evidence"]["variant_id"]
    for fill, (receipt, _run_dir, variant_id) in variants.items():
        assert receipt["evidence"]["variant_id"] == variant_id
        assert receipt["spec_hash"] == variant_id, "the receipt binds its own spec hash"
        assert receipt["evidence"]["variants_tried"] == 1
        assert receipt["ledger_receipt"] == {"status": "not_requested", "mode": "smoke"}
    for _fill, (_receipt, run_dir, variant_id) in variants.items():
        report_text = (run_dir / "REPORT.md").read_text()
        assert "by engine.report v" in report_text
        assert f"Variant ID: {variant_id}" in report_text
        assert "Variants tried: 1" in report_text
    mid_hash = variants["mid"][2]
    ask_hash = variants["ask"][2]
    assert f"Variant ID: {ask_hash}" not in (variants["mid"][1] / "REPORT.md").read_text()
    assert f"Variant ID: {mid_hash}" not in (variants["ask"][1] / "REPORT.md").read_text()

    refused_dir = tmp_path / "run-refused"
    bad_spec = experiment_spec_from_document(
        _experiment_document(economic_params={"fill": "mid", "slippage_bps": 2.0}))
    with pytest.raises(OpsError) as excinfo:
        experiments.run_experiment(bad_spec, tmp_path, refused_dir,
                                   runner=plan_aware_runner, mode="smoke")
    assert excinfo.value.code == "INVALID_EXPERIMENT_SPEC"
    assert len(calls) == 2, "the invalid plan never reached the runner"
    assert not refused_dir.exists(), "the refusal precedes any report or ledger effect"

    assert not (tmp_path / "experiments" / "LEDGER.csv").exists()
    assert not list(tmp_path.rglob("LEDGER.csv"))
